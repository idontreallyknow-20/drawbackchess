/** The ONE expiry rule for board-level effects: null turns = permanent, and a
 * countdown keeps the effect alive while above zero. Every tick site filters
 * through this — the rule used to be open-coded in three places, which is
 * exactly how an expiry-rule change would have desynced them. */
function effectActive(e: ActiveEffect): boolean {
  return e.turns == null || e.turns > 0;
}

/** Freeze and walnut bind to the piece standing on their square. Once that
 * piece is gone (captured, or removed/relocated by another buff) the effect
 * must go with it: a walnut or freeze marker can never linger on an empty
 * square or transfer onto a capturing enemy piece. Called after every move and
 * after every buff-driven board mutation. */
function pruneOrphanedSquareEffects(game: NerfGame) {
  const bs = game.buffs;
  if (!bs) return;
  bs.effects = bs.effects.filter((e) => {
    if (e.kind === "freeze" || e.kind === "walnut" || e.kind === "timed_loss" || e.kind === "cosmetic") {
      // A trade-off timer whose piece was captured (or otherwise vanished)
      // before it expired has nothing left to reclaim: drop it like a freeze.
      const p = game.board.pieces[e.sq];
      return !!p && p.color === e.owner;
    }
    // A square-list shield only protects pieces standing on its squares. When
    // a shielded piece moves away (without the shield-follow keeping up, e.g.
    // a buff relocated or removed it) or is captured, its square must drop
    // from the list, or the shield would later protect whatever owner piece
    // next steps onto that square. A whole-army shield (squares null) is
    // unbounded and never pruned; a shield whose list empties is gone.
    if (e.kind === "shield" && e.squares) {
      e.squares = e.squares.filter((sq) => {
        const p = game.board.pieces[sq];
        return !!p && p.color === e.owner;
      });
      return e.squares.length > 0;
    }
    return true;
  });
}

/** Fire trade-off timers (timed_loss) that have counted down to zero: the owner
 * pays the delayed price on their tracked piece before the expired effect is
 * filtered out. The piece is either removed or reverted to another type (a
 * temporary grant taken back). Never touches a king, and the loss is uncounted:
 * the piece is reclaimed by its own owner's bargain, not captured by the
 * opponent, so revive pools and material counters stay truthful. */
function fireExpiredTradeOffs(game: NerfGame) {
  const bs = game.buffs;
  if (!bs) return;
  for (const e of bs.effects) {
    if (e.kind !== "timed_loss" || e.turns == null || e.turns > 0) continue;
    const p = game.board.pieces[e.sq];
    if (!p || p.color !== e.owner || p.type === "k") continue;
    bs.historyDiverged = true;
    bs.mutations = (bs.mutations ?? 0) + 1;
    if (e.then === "demote" && e.into && e.into !== "k") {
      game.board.pieces[e.sq] = { ...p, type: e.into };
    } else {
      game.board.pieces[e.sq] = null;
    }
  }
}

/** True while a nerf is suspended (Grace Period) or removed (Nerf Breaker). */
export function nerfDisabled(game: NerfGame, color: Color): boolean {
  const bs = game.buffs;
  if (!bs) return false;
  if (bs.players[color].nerfRemoved) return true;
  return bs.effects.some(
    (e) => e.kind === "nerf_suspended" && e.owner === color && effectActive(e),
  );
}

/**
 * The RNG behind api.rng: buff-effect randomness (The Culling's victims, chaos
 * scatters, the Jackpot / apex grants...). Seeded STATELESSLY from public,
 * byte-identically-synced state — the ply count, the 64-square board signature,
 * and the acting color — never from any per-client secret.
 *
 * Why not slot.rng (the per-player nerf RNG, used here historically): that
 * stream only exists on the server. A client replica builds the OPPONENT's slot
 * as RNG(0) (their nerf seed is hidden) and a spectator replica seeds both
 * slots with a dummy, so any card effect that rolled on slot.rng removed
 * DIFFERENT pieces on every replica — the root cause of the "crazy powerup
 * desyncs the game" reports. Every replica does share the board and the move /
 * public-action record, so a seed derived purely from those replays the same
 * draws everywhere: server, both clients, spectators, arena replays, snapshot
 * restores.
 *
 * Stateless-per-event is deliberate (no persistent fx stream in
 * BuffMatchState): a hidden card whose hook draws but does nothing observable
 * never shifts anyone else's future draws, so replicas can never drift apart —
 * each event reseeds from state they all agree on. Within one event (one
 * makeBuffApi lifetime) successive draws walk one Mulberry32 stream, so
 * multi-draw effects stay properly varied. The board signature is taken at api
 * creation, which every apply path does per event (activation, hook loop,
 * instant pick), so two same-ply events by the same color are still separated
 * by the board change the first one made.
 */
function fxRng(game: NerfGame, me: Color): RNG {
  let seed = boardSignature(game.board);
  seed = Math.imul(seed ^ (game.board.history.length + 1), 0x9e3779b1);
  seed = Math.imul(seed ^ (me === "w" ? 0x517cc1b7 : 0x27220a95), 0x85ebca6b);
  // Also mix a digest of the public card state. Board+ply alone repeated
  // seeds byte-for-byte when two casts landed at the same position with no
  // board change between them — e.g. two Wheel of Fortune instants picked
  // back-to-back whose first wedge only touched the clock rolled the SAME
  // wedge every time ("I got +55 seconds five spins in a row"). Held-card
  // counts, spent/used flags, effect count, rerolls, and the mutation
  // counter all advance between such casts, are part of the byte-identical
  // synced state on every replica, and never leak a hidden card (counts
  // only, no identities).
  const bs = game.buffs;
  if (bs) {
    let d = (bs.mutations ?? 0) ^ ((bs.effects.length + 1) << 8);
    for (const c of ["w", "b"] as Color[]) {
      const ps = bs.players[c];
      let spent = 0;
      let used = 0;
      for (const b of ps.buffs) {
        if (b.spent) spent++;
        if (b.usedActivation) used++;
      }
      d = Math.imul(d ^ (ps.buffs.length + 1), 0x9e3779b1);
      d = Math.imul(d ^ (spent * 31 + used * 131 + ps.rerollsLeft * 7 + 1), 0x85ebca6b);
    }
    seed = Math.imul(seed ^ d, 0xc2b2ae35);
  }
  return new RNG(seed >>> 0);
}

export function makeBuffApi(game: NerfGame, me: Color): BuffApi {
  const bs = game.buffs!;
  const opp: Color = me === "w" ? "b" : "w";
  const slot = me === "w" ? game.white : game.black;
  // Every direct board mutation bumps the transient counter so apply paths
  // (playMove's hook loop, the game server's pick handling) can tell whether
  // a hook or init observably changed the board. Only counted when the board
  // actually changes, so a refused relocation or a no-op removal never
  // reveals a card that did nothing visible.
  const mutated = () => {
    bs.mutations = (bs.mutations ?? 0) + 1;
  };
  return {
    board: game.board,
    me,
    opp,
    bs,
    mine: bs.players[me],
    theirs: bs.players[opp],
    rng: fxRng(game, me),
    capturedFromMe: game.captured[opp],
    capturedByMe: game.captured[me],
    place: (sq, type, color) => {
      bs.historyDiverged = true;
      mutated();
      game.board.pieces[sq] = { type, color };
    },
    removePiece: (sq, opts) => {
      const p = game.board.pieces[sq];
      if (!p) return;
      bs.historyDiverged = true;
      mutated();
      game.board.pieces[sq] = null;
      // A piece destroyed by a buff is a real loss: count it as captured by
      // the other side so material counters and the owner's revivable pool
      // (Resurrect and friends) stay truthful. Kings are never removed by
      // buffs; the guard is a backstop. Whole-board rewrites (Perfect
      // Rewind, Genesis) and effect-expiry removals of summoned pieces pass
      // `uncounted` instead: those pieces were never lost to the opponent,
      // so counting them would corrupt the revive pools and any
      // capturedFromMe-based nerf conditions.
      if (p && p.type !== "k" && !opts?.uncounted) {
        game.captured[p.color === "w" ? "b" : "w"][p.type] += 1;
      }
    },
    relocate: (from, to) => {
      const p = game.board.pieces[from];
      // Nothing to relocate: bail before the write below could null out a
      // piece already standing on `to`.
      if (!p) return;
      // Anchor: an enemy piece bound by its owner's Anchor buff cannot be
      // pushed or swapped by my buffs (its own moves are unaffected).
      if (
        p &&
        p.color !== me &&
        bs.players[p.color].buffs.some(
          (b) => b.id === "anchor" && !b.spent && !b.nullified && b.state.sq === from,
        )
      ) {
        return;
      }
      // Pawns can never stand on rank 1 or rank 8: refuse the relocation
      // outright, whatever card asked for it (cards filter their destination
      // zones too; this is the backstop).
      if (p?.type === "p" && !pawnRankOk(to)) {
        return;
      }
      bs.historyDiverged = true;
      mutated();
      game.board.pieces[from] = null;
      game.board.pieces[to] = p;
    },
    setPieceType: (sq, type) => {
      bs.historyDiverged = true;
      const p = game.board.pieces[sq];
      if (p) {
        mutated();
        game.board.pieces[sq] = { ...p, type };
      }
    },
    setPieceColor: (sq, color) => {
      bs.historyDiverged = true;
      const p = game.board.pieces[sq];
      if (p) {
        mutated();
        game.board.pieces[sq] = { ...p, color };
      }
    },
    restoreCastling: () => {
      const homeR = me === "w" ? 0 : 7;
      const king = game.board.pieces[SQ(4, homeR)];
      if (!king || king.type !== "k" || king.color !== me) return;
      const kingside = game.board.pieces[SQ(7, homeR)];
      const queenside = game.board.pieces[SQ(0, homeR)];
      if (kingside?.type === "r" && kingside.color === me) {
        if (me === "w") game.board.castling.wk = true;
        else game.board.castling.bk = true;
      }
      if (queenside?.type === "r" && queenside.color === me) {
        if (me === "w") game.board.castling.wq = true;
        else game.board.castling.bq = true;
      }
    },
    removeMyNerf: () => {
      slot.nerf = FREED_NERF;
      slot.state = {};
      bs.players[me].nerfRemoved = true;
    },
    adjustClock: (req) => {
      (bs.clockFx ??= []).push({ caster: me, ...req });
    },
  };
}

/**
 * Squares `color` can strike through BUFF-granted augmented moves (a rook that
 * also steps diagonally, a camel knight, an amazon, the king's extended reach,
 * ...). Runs exactly the augmentMoves hooks legalMoves uses, but on a read-only
 * clone of the board with `color` to move, then returns only the target squares
 * of the moves those hooks ADDED beyond standard movement. Pure: it clones the
 * board and never mutates the live board, effects, or the draft RNG (augment
 * generators only read the board), so it is safe to call from anywhere and can
 * never desync. Feeds board.ts's attack test so a king attacked solely by an
 * augmented enemy piece is still detected (see gameInCheck / isInCheck).
 */
export function buffAugmentedAttacks(game: NerfGame, color: Color): Square[] {
  const bs = game.buffs;
  if (!bs || bs.diff) return [];
  const held = heldBuffs(game, color);
  if (held.length === 0) return [];
  const board = cloneBoard(game.board);
  board.turn = color;
  const view: NerfGame = { ...game, board };
  const api = makeBuffApi(view, color);
  const base = generateMoves(board);
  const augmented = base.slice();
  for (const { inst, def } of held) def.augmentMoves?.(augmented, inst, api);
  const squares: Square[] = [];
  for (let i = base.length; i < augmented.length; i++) squares.push(augmented[i].to);
  return squares;
}

/** Check detection that also honors buff-granted augmented moves: a king
 * attacked only via an augmented enemy piece is flagged in check, which plain
 * board.ts isInCheck (standard movement only) misses. Use this wherever game
 * (buff) context is available. */
export function gameInCheck(game: NerfGame, color: Color): boolean {
  const opp: Color = color === "w" ? "b" : "w";
  return isInCheck(game.board, color, buffAugmentedAttacks(game, opp));
}

function heldBuffs(game: NerfGame, color: Color): { inst: BuffInstance; def: Buff }[] {
  const bs = game.buffs;
  if (!bs) return [];
  return bs.players[color].buffs
    .filter((b) => !b.spent && !b.nullified)
    .map((inst) => ({ inst, def: BUFF_BY_ID[inst.id] }))
    .filter((x): x is { inst: BuffInstance; def: Buff } => !!x.def);
}

// --- Buff-aware search support (backlog A13) --------------------------------
//
// `negamax` searches bare BoardStates, and only `legalMoves` runs
// `def.augmentMoves`, so before this every move-granting buff existed at the
// root and nowhere below it: the bot played a move that only its card made
// legal, then evaluated every follow-up as if it did not hold the card.
// `buildSearchBuffs` + `applySearchAugments` give the search the same augment
// hooks per node, under three constraints that made the change risky enough to
// be filed on its own.
//
// 1. NOTHING LIVE IS REACHABLE. The audit behind this (scripts/audit-augment-
//    purity.ts) found ten generators that write `inst.state` from inside
//    `augmentMoves` — the "use it or lose it" bookkeeping shared by the nine
//    lossy openers and Dryad Grove sets `armed` / `offered` whenever the move
//    is on offer. Called per node that would arm a real card off a hypothetical
//    position and burn its charge in the real game. Rather than allowlisting
//    the pure ones (283 hooks, 71 of which never fire in any probe position, so
//    an allowlist would be guessing), the search runs against a private view:
//    cloned instances, a cloned BuffMatchState, cloned captured pools and
//    cloned player slots. Every mutator on the api therefore writes into
//    throwaway objects. An impure generator can mis-score a search; it cannot
//    reach the game.
//
//    The same audit found ZERO `api.rng` draws in the entire library, and
//    `fxRng` is stateless anyway (seeded per call from the synced board, not a
//    persistent stream — see its comment), so calling these hooks per node
//    cannot advance anything a replica would have to agree about. The desync
//    hazard recorded against this task does not exist.
//
// 2. NO PER-NODE API REBUILD. `makeBuffApi` is ~20 closures; building one per
//    node is far too slow for a hot path. Instead exactly two apis are built
//    per search (one per side) over mutable view games, and the only per-node
//    work is retargeting `.board` at the node's board. That is a shared
//    object, but every generator runs synchronously inside
//    `applySearchAugments` immediately after the retarget and nothing in the
//    library retains the api, so there is no live range for it to go stale in;
//    and because the view is entirely clones, a stale read could only mis-score.
//
// 3. EXPIRY IS MODELLED. `timedAugment(n)` lasts the owner's next n moves, so
//    applying it at every ply would over-value a three-turn card at depth 12 —
//    trading one bias for another. The side to move at ply p has played
//    exactly `p >> 1` of its own moves to get there, so the per-ply table below
//    holds instances whose counters are already decremented by that much, and
//    a card drops out of the table at the ply it expires. Charge-limited
//    augments (`augment` / `lossyAugment`, 133 of the 283) are spent by PLAYING
//    the granted move rather than by time passing, so they carry a bit in a
//    spent mask that negamax threads down each line: once a line plays the
//    granted move, deeper plies in that line stop being offered it.

/** One held move-granting buff, prepared for a specific search ply. */
export interface SearchAugment {
  def: Buff;
  /** Private clone of the live instance, timed counter already aged to the ply. */
  inst: BuffInstance;
  /** Bit in the spent mask for charge-limited augments, or -1 for timed ones. */
  chargeBit: number;
}

/** Everything the search needs to reproduce `legalMoves`'s augment step at an
 *  interior node, precomputed once per search. */
export interface SearchBuffs {
  /** byPly[p] = augments available to the side to move at ply p. */
  byPly: SearchAugment[][];
  /** api[p & 1] — the BuffApi of the side to move at ply p (parity 0 = root). */
  api: [BuffApi, BuffApi];
  /** The mutable private view games behind those apis. */
  view: [NerfGame, NerfGame];
  /** bitOf[p & 1] maps a granted move's `via` id to its spent-mask bit. */
  bitOf: [Map<string, number>, Map<string, number>];
}

/** Spent-mask bits available per side. Sides hold single-digit numbers of
 *  move-granting cards in practice; a card past the cap is simply left out of
 *  the search (falling back to the old root-only behaviour for that card)
 *  rather than being given an untracked, permanently unspent charge. */
const MAX_AUGMENT_SLOTS = 16;

function cloneForSearch(game: NerfGame, bs: BuffMatchState): NerfGame {
  const clonePlayer = (c: Color) => {
    const ps = bs.players[c];
    return {
      ...ps,
      buffs: ps.buffs.map((b) => ({ ...b, state: { ...b.state } })),
      flags: { ...ps.flags },
      revived: { ...ps.revived },
      inventory: ps.inventory ? { ...ps.inventory } : undefined,
    };
  };
  const searchBs: BuffMatchState = {
    ...bs,
    effects: bs.effects.map((e) => ({ ...e })),
    extraMoves: { ...bs.extraMoves },
    skips: { ...bs.skips },
    players: { w: clonePlayer("w"), b: clonePlayer("b") },
  };
  return {
    ...game,
    buffs: searchBs,
    white: { ...game.white },
    black: { ...game.black },
    captured: { w: { ...game.captured.w }, b: { ...game.captured.b } },
    fx: undefined,
  };
}

/**
 * Prepare the held move-granting buffs of both sides for a search rooted at
 * `game`, covering plies 0..maxPly. Returns null when there is nothing to do
 * (no draft game, a Chess Diff sub-game, or neither side holds a card with an
 * `augmentMoves` hook), which is the overwhelmingly common case and costs the
 * search nothing.
 */
export function buildSearchBuffs(game: NerfGame, maxPly: number): SearchBuffs | null {
  const bs = game.buffs;
  // A Chess Diff is plain chess: legalMoves runs no augments there either.
  if (!bs || bs.diff) return null;

  const me = game.board.turn;
  const opp: Color = me === "w" ? "b" : "w";
  const sides: [Color, Color] = [me, opp];

  const live = sides.map((c) => heldBuffs(game, c).filter((h) => !!h.def.augmentMoves));
  if (!live[0].length && !live[1].length) return null;

  // Two private views, one per side, so a generator that reaches for a mutator
  // writes into a clone instead of the live game.
  const view: [NerfGame, NerfGame] = [cloneForSearch(game, bs), cloneForSearch(game, bs)];
  const api: [BuffApi, BuffApi] = [makeBuffApi(view[0], me), makeBuffApi(view[1], opp)];
  const bitOf: [Map<string, number>, Map<string, number>] = [new Map(), new Map()];

  const byPly: SearchAugment[][] = [];
  for (let ply = 0; ply <= maxPly; ply++) byPly.push([]);

  for (let parity = 0; parity < 2; parity++) {
    let nextBit = 0;
    for (const { inst, def } of live[parity]) {
      const charges = inst.state.charges;
      let chargeBit = -1;
      if (typeof charges === "number") {
        // A charge already exhausted in the real game grants nothing at all.
        if (charges <= 0) continue;
        if (nextBit >= MAX_AUGMENT_SLOTS) continue;
        chargeBit = parity * MAX_AUGMENT_SLOTS + nextBit++;
        bitOf[parity].set(def.id, chargeBit);
      }
      const turns = inst.state.turns;
      // The side to move at ply p has played p >> 1 of its own moves getting
      // there, which is exactly what tickTurns would have decremented.
      for (let ply = parity; ply <= maxPly; ply += 2) {
        const state = { ...inst.state };
        if (typeof turns === "number") {
          const aged = turns - (ply >> 1);
          if (aged <= 0) break; // expired here, and at every deeper ply
          state.turns = aged;
        }
        byPly[ply].push({ def, inst: { ...inst, state }, chargeBit });
      }
    }
  }

  if (byPly.every((l) => !l.length)) return null;
  return { byPly, api, view, bitOf };
}

/**
 * Append the buff-granted moves available to the side to move at `ply` on
 * `board`, exactly as `legalMoves` would at the root. `spentMask` carries the
 * charge-limited augments already used further up this line.
 *
 * Nerf filters, shields, walls and zone effects are NOT reapplied here: the
 * search has always generated interior moves with bare `generateMoves`, so
 * those were already invisible below the root and this change neither adds to
 * nor removes from that gap. It closes only the augment half.
 */
export function applySearchAugments(
  sb: SearchBuffs,
  board: BoardState,
  ply: number,
  spentMask: number,
  moves: Move[],
): void {
  const list = sb.byPly[ply];
  if (!list || !list.length) return;
  const parity = ply & 1;
  // Retarget the private view at this node's board. Generators run
  // synchronously below and none of them retains the api, so the shared object
  // is never read outside this call.
  sb.view[parity].board = board;
  sb.api[parity].board = board;
  for (const a of list) {
    if (a.chargeBit >= 0 && (spentMask & (1 << a.chargeBit)) !== 0) continue;
    try {
      a.def.augmentMoves!(moves, a.inst, sb.api[parity]);
    } catch {
      // A generator that throws on some hypothetical position must not take
      // the whole search down with it; it just contributes nothing here.
    }
  }
}

/** Fold a played move into the spent mask: a charge-limited augment used in
 *  this line is not offered again deeper in it. */
export function markAugmentSpent(sb: SearchBuffs, ply: number, move: Move, spentMask: number): number {
  if (!move.via) return spentMask;
  const bit = sb.bitOf[ply & 1].get(move.via);
  return bit === undefined ? spentMask : spentMask | (1 << bit);
}

/** A barred effect whose squares form exactly one complete file or rank is a
 * board-splitting WALL, not just a no-landing zone (Fault Line, Great Wall,
 * Great Divide, Sundering, and the whole-file / whole-rank hexes all build one
 * such line per pick). Blocking only the landing square lets a piece jump the
 * wall: a knight leaps clean over the barred squares, and a slider glides
 * through the empty ones. Detecting this shape lets legalMoves also reject any
 * move that CROSSES the line. Returns the wall's axis and line index, or null
 * for partial barred zones (Bunker, the Kraken 3x3 seal, a multi-rank scorched
 * band) which only block landing. A thick band (two or more adjacent ranks or
 * files) needs no crossing rule: a knight cannot leap a two-wide barrier, so
 * its landing square always falls inside the band and the landing filter alone
 * stops it. */
function wallLine(squares: Square[]): { axis: "file" | "rank"; line: number } | null {
  if (squares.length !== 8) return null;
  const f0 = FILE(squares[0]);
  if (squares.every((s) => FILE(s) === f0) && new Set(squares.map((s) => RANK(s))).size === 8) {
    return { axis: "file", line: f0 };
  }
  const r0 = RANK(squares[0]);
  if (squares.every((s) => RANK(s) === r0) && new Set(squares.map((s) => FILE(s))).size === 8) {
    return { axis: "rank", line: r0 };
  }
  return null;
}

export function legalMoves(game: NerfGame): Move[] {
  if (game.result) return [];
  let all = generateMoves(game.board);
  // Chess Diff sub-game: a plain game of chess under STANDARD rules. No nerf
  // filters, no buff augments, no zone effects (stashed empty anyway), and no
  // pocket drops - but, unlike the rest of the site (decided by king capture),
  // you may not leave your own king in check. Filter the pseudo-legal moves
  // down to the ones that keep the mover's king safe, so the diff is won by
  // checkmate and drawn by stalemate (see resolveNoMoves), never by a king
  // walking into capture.
  if (game.buffs?.diff) {
    // No nerfs run during a diff; drop any pre-diff report so the fx layer
    // never narrates a stale constraint.
    game.lastNerfFilter = null;
    const mover = game.board.turn;
    const opp: Color = mover === "w" ? "b" : "w";
    // Opponent's attack map on the pre-move board, reused for the castling test.
    const attacked = attackedBy(game.board, opp);
    return all.filter((m) => {
      if (m.castle) {
        // Standard castling: the king may not castle out of, through, or into
        // check, so all three king-path squares (from, transit, destination)
        // must be unattacked. generateMoves deliberately allows nerf-chess
        // castling through check, so the diff has to re-impose the real rule.
        const transit = m.castle === "k" ? SQ(5, RANK(m.from)) : SQ(3, RANK(m.from));
        return !attacked.has(m.from) && !attacked.has(transit) && !attacked.has(m.to);
      }
      // Any other move is legal iff it does not leave the mover's king in check.
      return !isInCheck(makeMove(game.board, m), mover);
    });
  }
  const me = game.board.turn;
  const opp: Color = me === "w" ? "b" : "w";
  const slot = me === "w" ? game.white : game.black;
  const bs = game.buffs;
  let frozenOwnCount = 0;

  if (bs) {
    // Frozen pieces cannot move at all. Walnuts are a lighter, distinct
    // lockdown: a heavy nut can still shuffle ONE square (a king-step), so it
    // plays differently from a freeze instead of being a reskin of it.
    const frozen = new Set(
      bs.effects
        .filter((e) => e.kind === "freeze" && e.owner === me && effectActive(e))
        .map((e) => (e.kind === "freeze" ? e.sq : -1)),
    );
    const walnut = new Set(
      bs.effects
        .filter((e) => e.kind === "walnut" && e.owner === me && effectActive(e))
        .map((e) => (e.kind === "walnut" ? e.sq : -1)),
    );
    frozenOwnCount = frozen.size + walnut.size;
    if (frozen.size) all = all.filter((m) => !frozen.has(m.from));
    if (walnut.size)
      all = all.filter(
        (m) =>
          !walnut.has(m.from) ||
          (Math.abs(FILE(m.to) - FILE(m.from)) <= 1 && Math.abs(RANK(m.to) - RANK(m.from)) <= 1),
      );

    // My buffs may add moves. Nerf constraints are applied afterwards, so a
    // handicap still governs buff-granted movement.
    const api = makeBuffApi(game, me);
    for (const { inst, def } of heldBuffs(game, me)) {
      def.augmentMoves?.(all, inst, api);
    }
  }

  if (slot.nerf.filterMoves && !nerfDisabled(game, me)) {
    const ctx = makeContext(game, slot.color);
    const beforeNerf = all;
    const filtered = slot.nerf.filterMoves(all, slot.state, ctx);
    // Safety net: a move-restriction nerf must never zero out the mover's
    // options. That is a self-stalemate / soft-lock, not an intended loss
    // (loss conditions run separately via checkLoss). The rule harness only
    // probes each nerf from the opening, so nerfs that empty the list in a
    // mid or endgame position (statue_king, no_mans_land, scorched_earth,
    // the no-backward family, etc.) slipped through. If a nerf empties the
    // list while legal moves existed, relax it for this one turn. Every such
    // nerf still shapes play on every turn where at least one legal move
    // survives its filter, which is nearly all of them.
    const relaxed = filtered.length === 0 && beforeNerf.length > 0;
    all = filtered.length > 0 ? filtered : beforeNerf;
    // Report what the handicap just did, for the fx layer. Recomputed on every
    // call with an identical result for a given position, so overwriting is
    // harmless; playMove folds the freshest report into one event per ply.
    game.lastNerfFilter = nerfFilterReport(me, slot.nerf.id, beforeNerf, filtered, relaxed);
  } else {
    game.lastNerfFilter = null;
  }

  if (bs) {
    // Opponent protections and zone effects restrict my options.
    for (const e of bs.effects) {
      if (!effectActive(e)) continue;
      switch (e.kind) {
        case "shield":
          if (e.owner === opp) {
            all = all.filter((m) => {
              const cap = m.capturedSquare ?? (m.captured ? m.to : null);
              if (cap == null) return true;
              // A shield never protects the king itself. King invulnerability
              // is exclusively king_safe / Immortal King (documented, and it
              // carries a drawback). Without this, a permanent square shield
              // parked on the king (Sanctuary) or a whole-army shield would
              // make the king uncapturable forever and the game unwinnable.
              if (game.board.pieces[cap]?.type === "k") return true;
              return e.squares ? !e.squares.includes(cap) : false;
            });
          }
          break;
        case "barred": {
          // A wall never seals the king away from capture. Winning is king
          // capture (there is no checkmate), so a permanent barred file or rank
          // sitting over the enemy king would otherwise soft-lock the game as
          // unwinnable (the Sundering / Great Divide / Fissure trap). A move
          // that captures the king ignores the wall; every other move into a
          // barred square is still blocked.
          if (e.against === me) {
            all = all.filter((m) => m.captured === "k" || !e.squares.includes(m.to));
            // Board-split walls (a full barred file or rank) must also block any
            // move that CROSSES the line, not merely one that lands on it: a
            // knight leaps over the barred squares and a slider glides through
            // the empty ones, so the landing filter above lets both jump the
            // wall. Reject moves whose from/to sit on opposite sides of the
            // line. King captures stay exempt (same unwinnability guard as
            // above). Non-soft-lock: never strand the mover. If blocking
            // crossings would empty the list (every remaining piece is across
            // the wall from where it must go), relax this wall for the turn so
            // the mover keeps its moves on its own side.
            const wall = wallLine(e.squares);
            if (wall) {
              const side = (sq: Square) =>
                (wall.axis === "file" ? FILE(sq) : RANK(sq)) - wall.line;
              const kept = all.filter(
                (m) => m.captured === "k" || side(m.from) * side(m.to) >= 0,
              );
              if (kept.length > 0) all = kept;
            }
          }
          break;
        }
        case "king_safe":
          if (e.owner === opp) all = all.filter((m) => m.captured !== "k");
          break;
        case "no_pawn_advance":
          if (e.against === me) {
            all = all.filter((m) => !(m.piece === "p" && FILE(m.from) === FILE(m.to)));
          }
          break;
        case "king_only":
          if (e.against === me) all = all.filter((m) => m.piece === "k");
          break;
        case "short_leash":
          // Berserker's hangover: the owner may only step one square (king
          // distance) with any piece. King captures stay exempt so the game
          // is always winnable, and if the leash would strand the mover with
          // no move it is relaxed for the turn rather than soft-locking.
          if (e.owner === me) {
            const kept = all.filter(
              (m) =>
                m.captured === "k" ||
                Math.max(Math.abs(FILE(m.to) - FILE(m.from)), Math.abs(RANK(m.to) - RANK(m.from))) <= 1,
            );
            if (kept.length > 0) all = kept;
          }
          break;
      }
    }
    const oppApi = makeBuffApi(game, opp);
    for (const { inst, def } of heldBuffs(game, opp)) {
      if (def.filterOpponentMoves) all = def.filterOpponentMoves(all, inst, oppApi);
    }
    // Chained-move king guard: while a player is bursting through extra
    // moves or opponent skips, capturing the king is off the table until the
    // opponent has played one reply move. The final chained move may still
    // give check or create threats; it just cannot end the game on the spot.
    if (bs.chainKingGuard === me || bs.extraMoves[me] > 0 || bs.skips[opp] > 0) {
      all = all.filter((m) => m.captured !== "k");
    }
    // Invulnerability must not also deliver the win. A piece that cannot be
    // captured this turn (shielded by my own shield, or my king under a
    // king_safe ward) may not be the one to capture the enemy king: an
    // untouchable attacker would be a riskless, uncounterable finish, which is
    // exactly the "too strong" case. You have to expose a piece to end the
    // game. Any capturable piece may still take the king, so the position is
    // never made unwinnable; the guard below relaxes if it would empty the list.
    {
      const myShieldZones = bs.effects
        .filter((e) => e.kind === "shield" && e.owner === me && effectActive(e))
        .map((e) => (e.kind === "shield" ? e.squares : null));
      const myKingSafe = bs.effects.some(
        (e) => e.kind === "king_safe" && e.owner === me && effectActive(e),
      );
      if (myShieldZones.length > 0 || myKingSafe) {
        const untouchable = (sq: Square) =>
          myShieldZones.some((squares) => (squares ? squares.includes(sq) : true)) ||
          (myKingSafe && game.board.pieces[sq]?.type === "k");
        const guarded = all.filter((m) => m.captured !== "k" || !untouchable(m.from));
        if (guarded.length > 0) all = guarded;
      }
    }
    // Panic step: while mass freeze (3 or more of my pieces frozen) is
    // active, my king keeps its plain one-square quiet steps regardless of
    // zone effects, so a freeze plus extra-move stack can never leave a side
    // with no meaningful reply.
    if (frozenOwnCount >= 3) {
      for (const m of generateMoves(game.board)) {
        if (m.piece !== "k" || m.captured) continue;
        if (Math.abs(FILE(m.to) - FILE(m.from)) > 1 || Math.abs(RANK(m.to) - RANK(m.from)) > 1) {
          continue;
        }
        if (!all.some((x) => x.from === m.from && x.to === m.to)) all.push(m);
      }
    }

    // Crazyhouse-style inventory drops. Purely ADDITIVE and appended last, after
    // every nerf/effect filter and relax rule, so a drop never displaces a piece
    // move nor gets swept up by the "relax when the list would empty" guards: a
    // player who can only drop is still not stalemated (drops count as legal
    // moves in resolveNoMoves). A drop lands on an EMPTY square only, so it can
    // never capture anything (the enemy king included), which is exactly why the
    // chainKingGuard / shield king-capture guards above leave drops untouched.
    // Pawns may never be dropped onto rank 1 or 8, and a king is never in a
    // pocket.
    const inv = bs.players[me].inventory;
    if (inv) {
      for (const key of Object.keys(inv) as PieceType[]) {
        const count = inv[key] ?? 0;
        if (count <= 0 || key === "k") continue;
        for (let sq = 0; sq < 64; sq++) {
          if (game.board.pieces[sq]) continue;
          if (key === "p" && !pawnRankOk(sq)) continue;
          all.push({ from: sq, to: sq, piece: key, color: me, drop: key });
        }
      }
    }
  }
  return all;
}

// ---------------------------------------------------------------------------
// Chess Diff sub-game (see ChessDiffState in buff.ts and the card in
// buffs/library.ts). While bs.diff is set the game is a plain 1+0 game of
// chess: no drafts roll, no nerfs filter, no buffs augment or activate, and
// board effects are stashed away. The functions below decide the diff and
// resume the paused game.
// ---------------------------------------------------------------------------

/** Decide the running Chess Diff: restore the paused game's board (keeping
 * the full, continuous move history so ply counters never drift), effects and
 * tempo counters, and hand ONLY the diff's winner a guaranteed apex (tier 9)
 * (tier 10) card. A drawn diff grants nobody anything. Deterministic: every
 * replica reaches this through the same move/action record. */
function endChessDiff(game: NerfGame, winner: Color | "draw") {
  const bs = game.buffs;
  const diff = bs?.diff;
  if (!bs || !diff) return;
  // The move record keeps counting through the diff, so the restored board
  // carries the live (pre-diff + diff) history, not the stale stashed one.
  const fullHistory = game.board.history;
  // How many plies the sub-game added: the live history minus the pre-diff
  // snapshot stashed on the saved board. Read before the saved board is
  // re-adopted below (after which savedBoard.history IS fullHistory).
  const diffPlies = fullHistory.length - diff.savedBoard.history.length;
  game.board = diff.savedBoard;
  game.board.history = fullHistory;
  bs.effects = diff.savedEffects;
  bs.extraMoves = diff.savedExtraMoves;
  bs.skips = diff.savedSkips;
  bs.chainKingGuard = diff.savedChainKingGuard;
  bs.diff = undefined;
  // The buff-draft cadence is frozen for the whole diff (no drafts run during
  // it), but the diff's own plies still inflate the shared history. Shift the
  // draft threshold forward by exactly those plies so the resumed game keeps
  // its pre-diff distance to the next draft, instead of firing a backlog of
  // offers, one per move, until the frozen counter catches up to the now
  // longer history.
  if (bs.nextDraftAtPly != null && diffPlies > 0) {
    bs.nextDraftAtPly += diffPlies;
  }
  // The board was rewritten twice (into and out of the diff): history can no
  // longer reproduce it, so replay-based checks stay off.
  bs.historyDiverged = true;
  if (winner !== "draw") {
    // Balance pass: the diff's prize is a guaranteed APEX (tier 9) card, one
    // band below the mythic it used to pay out.
    grantGuaranteedTier9(makeBuffApi(game, winner));
  }
  // Resume the paused game exactly like a turn handover: the restored mover's
  // nerf turn-start runs, and a lockdown that was pending when the game
  // paused still force-passes rather than soft-locking.
  applyTurnStart(game);
  resolveNoMoves(game);
}

/** A player flagged (ran out of the diff's 1+0 clock) during a Chess Diff:
 * the other side wins the diff and the paused game resumes. Recorded by the
 * game server as a draft action so every replica replays the same outcome. */
export function resolveDiffFlag(game: NerfGame, flagged: Color) {
  if (!game.buffs?.diff || game.result) return;
  endChessDiff(game, flagged === "w" ? "b" : "w");
}

export function checkLossConditions(game: NerfGame): GameResult | null {
  // King capture check first. The FIRST king captured ends the game on the
  // spot: the capturer wins, full stop, even if their own king was hanging
  // (owner rule: "when you capture the king it's game, no more other stuff").
  // The former mutual-capture draw was removed under REPLAY_VERSION 9. The
  // both-kings-gone edge (a board wipe that somehow cleared both) stays a
  // draw as the only sane reading of an empty throne room.
  const captured = kingCaptured(game.board);
  if (captured) {
    const winner: Color = captured === "w" ? "b" : "w";
    if (findKing(game.board, winner) == null) {
      return { winner: "draw", reason: "both kings gone" };
    }
    return { winner, reason: "king captured" };
  }
  // Chess Diff sub-game: nerf loss conditions are suspended with the nerfs
  // themselves — only king capture decides the diff.
  if (game.buffs?.diff) return null;
  for (const color of ["w", "b"] as Color[]) {
    const slot = color === "w" ? game.white : game.black;
    if (!slot.nerf.checkLoss || nerfDisabled(game, color)) continue;
    const ctx = makeContext(game, color);
    const res = slot.nerf.checkLoss(slot.state, ctx);
    if (res) {
      return { winner: color === "w" ? "b" : "w", reason: `${slot.nerf.name}: ${res.reason}` };
    }
  }
  return null;
}

/** Apply a crazyhouse-style inventory drop onto a fresh board copy: place the
 * dropped piece on the (empty) target square, clear any stale en passant, hand
 * the turn to the opponent, and record the move in history so the ply count and
 * the move stream stay in lockstep with normal moves. The board is mutated
 * outside makeMove (a drop's origin square is empty, so a history replay through
 * makeMove could not reproduce it), so playMove sets bs.historyDiverged. */
function applyDrop(board: BoardState, move: Move): BoardState {
  const nb = cloneBoard(board);
  nb.pieces[move.to] = { type: move.drop!, color: move.color };
  nb.epTarget = null;
  nb.turn = move.color === "w" ? "b" : "w";
  if (move.color === "b") nb.fullmove++;
  // A drop is neither a pawn push nor a capture; it counts toward the fifty-move
  // clock like any other quiet move.
  nb.halfmove = nb.halfmove + 1;
  nb.history.push(move);
  return nb;
}

/** A cheap fingerprint of the 64 board squares (piece type + color per square,
 * position implicit in the loop order). The onMovePlayed reveal-detection uses
 * it to notice ANY board change a hook makes, including a direct `pieces[]`
 * write that never went through the BuffApi (only the BuffApi bumps
 * bs.mutations). A hook that removes, summons, or moves a piece MUST be revealed
 * to replicas, or they cannot replay the mutation and the boards desync
 * permanently (dtState never carries the board). Keying the detection on this
 * signature instead of trusting every hook to route through the api closes that
 * gap systemically, so no removal (or any board mutation) inside a hook can be
 * skipped by the reveal. */
function boardSignature(board: BoardState): number {
  let h = 2166136261;
  for (let sq = 0; sq < 64; sq++) {
    const p = board.pieces[sq];
    const code = p ? (p.color === "w" ? 1 : 7) + "pnbrqk".indexOf(p.type) : 0;
    h = Math.imul(h ^ code, 16777619);
  }
  return h >>> 0;
}

export function playMove(game: NerfGame, move: Move): NerfGame {
  if (game.result) return game;
  let nextBoard: BoardState;
  if (move.drop) {
    nextBoard = applyDrop(game.board, move);
  } else {
    nextBoard = makeMove(game.board, move);
    // makeMove refused the move (empty origin square or the self-capture
    // backstop): treat the whole ply as a no-op. Counting the capture or
    // ticking effect timers against a board that did not change would desync
    // the capture pools (revives) and effect clocks from the board itself.
    if (nextBoard === game.board) return game;
  }
  if (move.captured) {
    game.captured[move.color][move.captured] += 1;
  }
  game.board = nextBoard;
  // Fresh fx cycle: the log narrates exactly this ply's observable moments.
  beginFxCycle(game);
  const bs = game.buffs;
  if (move.drop && bs) {
    // The board changed outside history-replayable makeMove: suspend the
    // replay-based repetition check and spend one piece from the pocket. Bump
    // mutations so apply paths see the direct board change, exactly like the
    // BuffApi's place()/removePiece() do. Both clients replay the same drop
    // move from the shared move stream, so the pocket stays in lockstep; the
    // synced inventory (draftStateFor / mergeDraftState) is the safety net.
    bs.historyDiverged = true;
    bs.mutations = (bs.mutations ?? 0) + 1;
    const pocket = bs.players[move.color].inventory;
    if (pocket && (pocket[move.drop] ?? 0) > 0) {
      pocket[move.drop] = (pocket[move.drop] ?? 0) - 1;
      if ((pocket[move.drop] ?? 0) <= 0) delete pocket[move.drop];
    }
  }
  if (bs) {
    // A reply move from the other side lifts the chained-move king guard.
    if (bs.chainKingGuard && bs.chainKingGuard !== move.color) bs.chainKingGuard = undefined;
    // Buff bookkeeping: piece tracking, charge consumption, timed passives.
    // Record which hooks observably fired (a board mutation or a new board
    // effect): the game server reveals those cards to the table, because a
    // replica that does not know a card's identity cannot replay its hook,
    // and a skipped board mutation is a permanent desync. State-only changes
    // (charge counters) stay private; dtState frames resync those.
    const fired: { color: Color; index: number }[] = [];
    // Chess Diff sub-game: held buffs are dormant — their hooks reference the
    // paused board and must not fire on diff moves.
    for (const color of bs.diff ? [] : (["w", "b"] as Color[])) {
      const api = makeBuffApi(game, color);
      for (const { inst, def } of heldBuffs(game, color)) {
        if (!def.onMovePlayed) continue;
        const effectRefsBefore = snapshotEffects(game);
        const effectsBefore = bs.effects.length;
        const mutationsBefore = bs.mutations ?? 0;
        const clockFxBefore = bs.clockFx?.length ?? 0;
        const sigBefore = boardSignature(game.board);
        def.onMovePlayed(inst, move, api);
        // Reveal the card to replicas when its hook did anything observable: a
        // new/removed board effect, a BuffApi mutation-counter bump, a raw
        // board change the signature catches (a direct pieces[] write that never
        // touched the counter), OR a clock adjustment. The signature is the
        // systemic backstop that guarantees no removal (or any board mutation)
        // inside a hook can be skipped by the reveal, which would desync the
        // replica's board. Clock requests are already visible on the clock UI
        // the moment the server applies them, so revealing the card that made
        // one leaks nothing new — and it is what lets the client fire the
        // card's play art on every tick (a virus drain that changed the clock
        // but showed nothing on the board used to play no animation at all).
        if (
          bs.effects.length !== effectsBefore ||
          (bs.mutations ?? 0) !== mutationsBefore ||
          (bs.clockFx?.length ?? 0) !== clockFxBefore ||
          boardSignature(game.board) !== sigBefore
        ) {
          fired.push({ color, index: bs.players[color].buffs.indexOf(inst) });
          // Narrate the passive's fruition: the hook itself, any effect it
          // planted (with the victim derived per effect kind), and any clock
          // raid it requested. Derived-only; replicas replaying the same move
          // emit the same events.
          pushFxEvent(game, { kind: "passive-fired", color, cardId: def.id, ply: fxPly(game) });
          emitEffectDelta(game, effectRefsBefore, def.id);
          emitClockDelta(game, clockFxBefore, def.id);
        }
      }
    }
    bs.lastHookMutations = fired.length > 0 ? fired : undefined;
    // Shielded squares follow the shielded piece when its owner moves it.
    for (const e of bs.effects) {
      if (e.kind === "shield" && e.squares && move.color === e.owner) {
        const idx = e.squares.indexOf(move.from);
        if (idx >= 0) e.squares[idx] = move.to;
      }
      // A trade-off timer tracks its piece the same way, so the delayed loss
      // still lands on the right square after the piece moves.
      if (e.kind === "timed_loss" && e.owner === move.color && e.sq === move.from) {
        e.sq = move.to;
      }
      // A cosmetic dressing rides its piece (a giant pawn stays giant when it
      // advances). Pure visual: nothing else in the pipeline reads it.
      if (e.kind === "cosmetic" && e.owner === move.color && e.sq === move.from) {
        e.sq = move.to;
      }
    }
    // Tick down effects whose timer runs on the mover's turns.
    const beforeTick = snapshotEffects(game);
    for (const e of bs.effects) {
      if (e.turns != null && effectTickColor(e) === move.color) e.turns -= 1;
    }
    // Pay any trade-off timer that just reached zero before it is filtered out.
    fireExpiredTradeOffs(game);
    bs.effects = bs.effects.filter(effectActive);
    // A captured or buff-removed piece leaves its freeze/walnut behind; drop
    // those orphaned markers so they never haunt an empty or enemy-held square.
    pruneOrphanedSquareEffects(game);
    // Narrate everything that just ticked out or was pruned.
    emitEffectDelta(game, beforeTick);
  }
  // Check loss conditions
  const result = checkLossConditions(game);
  if (result) {
    // Chess Diff sub-game: a decided diff ends the DIFF, never the match. The
    // winner takes the apex prize (a mutual king capture is a drawn diff: nobody
    // does), the paused game resumes, and play continues.
    if (bs?.diff) {
      endChessDiff(game, result.winner === "draw" || result.winner == null ? "draw" : result.winner);
      return game;
    }
    game.result = result;
    return game;
  }
  // Standard draw rules: fifty moves without a capture or pawn move, and
  // threefold repetition of the same position with the same side to move.
  // These run inside playMove so every consumer (AI games, the multiplayer
  // worker, and client-side replays of server move lists) agrees on when a
  // game is drawn.
  if (game.board.halfmove >= 100) {
    // Fifty quiet moves inside a Chess Diff draw the DIFF (its halfmove clock
    // started at zero), not the match.
    if (bs?.diff) {
      endChessDiff(game, "draw");
      return game;
    }
    game.result = { winner: "draw", reason: "draw by the fifty-move rule" };
    return game;
  }
  // A repetition needs at least 8 reversible plies, so skip the history
  // replay until then. Once a buff has mutated the board directly the replay
  // no longer reproduces the position (it would crash on moves whose pieces
  // were summoned or removed outside history), so repetition detection is
  // suspended for the rest of the game.
  if (game.board.halfmove >= 8 && !bs?.historyDiverged && countRepetitions(game.board) >= 3) {
    game.result = { winner: "draw", reason: "draw by threefold repetition" };
    return game;
  }
  if (bs) {
    // Turn manipulation: extra moves keep the turn with the mover; skips hand
    // it straight back. En passant is cleared on any irregular turn flow.
    if (bs.extraMoves[move.color] > 0) {
      bs.extraMoves[move.color] -= 1;
      game.board.turn = move.color;
      game.board.epTarget = null;
      bs.chainKingGuard = move.color;
    } else if (bs.skips[game.board.turn] > 0) {
      bs.skips[game.board.turn] -= 1;
      game.board.turn = move.color;
      game.board.epTarget = null;
      bs.chainKingGuard = move.color;
    }
    // Buff draft cadence: both players draft at the same time. The shared
    // trigger runs on total plies (a full round is two plies), so neither
    // side ever runs a draft ahead of the other. White rolls first for a
    // stable RNG stream; draft-block effects eat offers individually.
    // Suspended entirely while a Chess Diff runs: no drafts during the diff.
    // The trigger stays put while it runs; endChessDiff shifts it past the
    // diff's plies on resume so the longer restored history does not fire a
    // backlog of offers.
    if (bs.diff) {
      applyTurnStart(game);
      resolveNoMoves(game);
      return game;
    }
    if (bs.nextDraftAtPly == null) {
      // Saved games from the per-player cadence era resume on the earlier
      // of the two old thresholds.
      bs.nextDraftAtPly = Math.min(bs.players.w.nextDraftAt, bs.players.b.nextDraftAt) * 2;
    }
    if (game.board.history.length >= bs.nextDraftAtPly) {
      bs.nextDraftAtPly += bs.cadence * 2;
      // One shared tier roll per round: both offers use the same pair.
      const tiers = rollSharedTiers(bs);
      for (const color of ["w", "b"] as Color[]) {
        const ps = bs.players[color];
        ps.nextDraftAt += bs.cadence;
        if (ps.offer) continue;
        if ((ps.flags.blockedDrafts ?? 0) > 0) {
          ps.flags.blockedDrafts = (ps.flags.blockedDrafts ?? 0) - 1;
          // Tell the victim explicitly (synced): their draft did not silently
          // vanish, an opponent card blocked it this round.
          ps.lastSkip = { atPly: game.board.history.length, reason: "blocked" };
        } else if (!rollOffer(bs, color, tiers, game.board)) {
          // Pool ran completely dry for this mode/tier: also announced.
          ps.lastSkip = { atPly: game.board.history.length, reason: "dry" };
        }
      }
    }
  }
  // Apply onTurnStart for the new mover BEFORE legal-move evaluation
  applyTurnStart(game);
  resolveNoMoves(game);
  // resolveNoMoves just ran legalMoves for the new mover, so the nerf filter's
  // report is fresh: fold it into this cycle's narration (one event per ply).
  if (!game.result) emitNerfFilterFx(game);
  return game;
}

/** The no-move rule, run whenever the side to move may have changed or lost
 * options: no moves available = loss for the side to move (their king will be
 * captured). In draft mode a player can be locked down purely by buff effects
 * (Mass Freeze, World End...). That is a forced pass, not a loss: their
 * effect timers tick as if they had moved and the turn goes back. If the
 * opponent is locked down too, the game is a draw. */
function resolveNoMoves(game: NerfGame) {
  if (game.result) return;
  if (legalMoves(game).length > 0) return;
  const bs = game.buffs;
  // Chess Diff sub-game: STANDARD chess endings, never the match. With no legal
  // move the mover is either checkmated (in check: the opponent wins the diff
  // and its apex prize) or stalemated (not in check: the diff is a draw and nobody
  // is rewarded). Legal moves are check-filtered (see legalMoves), so "no moves"
  // here is a true mate or stalemate, not a king simply left hanging.
  if (bs?.diff) {
    const mover = game.board.turn;
    const winner: Color = mover === "w" ? "b" : "w";
    endChessDiff(game, isInCheck(game.board, mover) ? winner : "draw");
    return;
  }
  if (bs && generateMoves(game.board).length > 0) {
    const stuck = game.board.turn;
    for (const e of bs.effects) {
      if (e.turns != null && effectTickColor(e) === stuck) e.turns -= 1;
    }
    fireExpiredTradeOffs(game);
    bs.effects = bs.effects.filter(effectActive);
    pruneOrphanedSquareEffects(game);
    game.board.turn = stuck === "w" ? "b" : "w";
    game.board.epTarget = null;
    applyTurnStart(game);
    if (legalMoves(game).length === 0) {
      game.result = { winner: "draw", reason: "mutual paralysis" };
    }
    return;
  }
  game.result = {
    winner: game.board.turn === "w" ? "b" : "w",
    reason: "no legal moves",
  };
}

export function currentHint(game: NerfGame, color: Color) {
  // Nerfs are suspended during a Chess Diff, so their hints are too.
  if (game.buffs?.diff) return null;
  const slot = color === "w" ? game.white : game.black;
  if (!slot.nerf.hint || nerfDisabled(game, color)) return null;
  if (game.result || game.board.turn !== color) return null;
  const ctx = makeContext(game, color);
  return slot.nerf.hint(slot.state, ctx, legalMoves(game));
}

