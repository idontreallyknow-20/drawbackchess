  clocks: { w: number; b: number };
  timeSec: number;
  incrementSec: number;
  timerState: PublicTimerState;
  /** Revealed nerf ids only (match result set, or slot revealed); else null. */
  revealedNerfs: { w: string | null; b: string | null };
