const AI_PIECE_VALUE: Record<PieceType, number> = { p: 1, n: 3, b: 3, r: 5, q: 9, k: 100 };

/** Score a candidate square for auto-targeting: enemy pieces dominate (by
 * value), then own pieces, then empty squares by centrality. */
/**
 * Does this card DESTROY the piece the player picks?
 *
 * The picker's normal instinct -- take the most valuable piece available -- is
 * right for a shield and catastrophic for a bomb, and nothing distinguished the
 * two. Detonate ("sacrifice one pawn to clear all pieces on its adjacent
 * squares") measured -42.5 points because the bot reliably picked its most
 * central pawn, whose neighbours in the opening are its OWN pieces, and blew up
 * its own position. Funeral Pyre and Blood Price failed the same way: three of
 * the five worst cards in the library shared this one cause.
 *
 * Derived from rules text rather than a per-card flag, so a card written later
 * is covered without anyone remembering to tag it.
 */
function pickIsSacrifice(def: Buff): boolean {
  const d = (def.description ?? "").toLowerCase();
  return (
    /\bsacrifice\b/.test(d) ||
    /destroy one of your own/.test(d) ||
    /\bone of your own pieces\b[^.]*\b(?:destroyed|removed|lost)\b/.test(d) ||
    // Crosses a sentence break on purpose: Funeral Pyre says "choose any of
    // your pieces (your king aside). It is removed, and every enemy piece
    // adjacent to it is destroyed" -- the removal lands in the NEXT sentence,
    // and a pattern that stopped at the full stop missed one of the three
    // cards this rule exists for.
    /\b(?:choose|pick) (?:any of )?your (?:own )?pieces?\b[\s\S]{0,90}\b(?:it )?is removed\b/.test(d)
  );
}

/**
 * Square score for a card that will destroy what it picks.
 *
 * Inverted on the owner's side -- cheapest piece wins -- and paid for by the
 * enemy material standing next to it, so a blast is aimed at a cluster of
 * theirs rather than at the middle of the board.
 */
function aiSacrificeScore(game: NerfGame, me: Color, sq: Square): number {
  const p = game.board.pieces[sq];
  if (!p) return 0;
  const opp: Color = me === "w" ? "b" : "w";
  let enemyNear = 0;
  let friendNear = 0;
  for (let t = 0; t < 64; t++) {
    if (t === sq) continue;
    if (Math.abs(FILE(t) - FILE(sq)) > 1 || Math.abs(RANK(t) - RANK(sq)) > 1) continue;
    const n = game.board.pieces[t];
    if (!n || n.type === "k") continue;
    if (n.color === opp) enemyNear += AI_PIECE_VALUE[n.type];
    else friendNear += AI_PIECE_VALUE[n.type];
  }
  // What the trade is worth: their material caught in it, minus ours, minus
  // the piece being spent. Offered as a positive score so the caller's
  // "highest wins" loop still works.
  return 100 + (enemyNear - friendNear - AI_PIECE_VALUE[p.type]) * 10;
}

function aiSquareScore(game: NerfGame, me: Color, sq: Square): number {
  const p = game.board.pieces[sq];
  const centrality = 7 - Math.max(Math.abs(FILE(sq) - 3.5), Math.abs(RANK(sq) - 3.5)) * 2;
  if (!p) return centrality;
  const base = AI_PIECE_VALUE[p.type] * 20;
  return p.color === me ? 100 + base + centrality : 1000 + base + centrality;
}

/**
 * Material on the board from `me`'s side, minus what `me` is about to lose.
 *
 * The second half is the part that matters. A card that MOVES one of your
 * pieces (a line sweep relocates the sweeper, a teleport lands it somewhere
 * new) can win material on the way and still be a blunder, because the piece
 * ends the turn standing where the opponent can take it. Counting only the
 * pieces on the board cannot see that, so a hanging piece is charged here at
 * its full value, less whatever it is standing on if a recapture is available.
 */
function aiPositionScore(game: NerfGame, me: Color): number {
  const opp: Color = me === "w" ? "b" : "w";
  let mine = 0;
  let theirs = 0;
  for (let sq = 0; sq < 64; sq++) {
    const p = game.board.pieces[sq];
    if (!p || p.type === "k") continue;
    if (p.color === me) mine += AI_PIECE_VALUE[p.type];
    else theirs += AI_PIECE_VALUE[p.type];
  }
  const theirAttacks = attackedBy(game.board, opp);
  const myAttacks = attackedBy(game.board, me);
  let hanging = 0;
  for (let sq = 0; sq < 64; sq++) {
    const p = game.board.pieces[sq];
    if (!p || p.color !== me || p.type === "k") continue;
    if (!theirAttacks.has(sq)) continue;
    // Defended pieces are not free, so only the excess is at risk. This is a
    // deliberately crude static exchange: it does not resolve a full capture
    // sequence, only "can they take it and do we get something back".
    hanging += myAttacks.has(sq) ? Math.max(0, AI_PIECE_VALUE[p.type] - 3) : AI_PIECE_VALUE[p.type];
  }
  return mine - theirs - hanging;
}

/**
 * Rank a fully-formed pick sequence by what the board actually looks like
 * afterwards, by applying it to a detached copy of the game.
 *
 * WHY THIS EXISTS
 *
 * `aiSquareScore` ranks a square by the single piece standing on it
 * (`1000 + value * 20` for an enemy). That is a reasonable first guess and it
 * is wrong in two ways that a sweep exposes at once. It cannot see what a card
 * catches along the way, so a line that eats three pawns scores below one that
 * ends on a knight; and it cannot see where the card leaves the piece it
 * moved, so the bot walks its queen onto a defended square to reach the
 * biggest target and hands over nine points for three.
 *
 * `queens_rampage` measured -13.6 win-rate points for its holder because of
 * this, at tier 7. The card is fine. The policy that fires it was not, and a
 * policy that plays a card badly does not just lose that game: it corrupts
 * every measurement the balance harness takes of every activated card.
 *
 * Simulation rather than more heuristics, because the geometry lives inside
 * each card's own mechanic and the picker cannot see it. The copy goes through
 * serialize/deserialize, so it shares no structure with the live game and, in
 * particular, carries its own RNG state: a card that rolls dice during this
 * trial does not advance the real stream and replays stay deterministic.
 */
function aiScoreSequence(game: NerfGame, color: Color, buffIndex: number, picks: BuffPick[]): number | null {
  const snap = serializeGame(game);
  const trial = deserializeGame(snap);
  if (!trial) return null;
  if (!activateBuff(trial, color, buffIndex, picks)) return null;
  return aiPositionScore(trial, color);
}

/**
 * How many alternatives the refinement pass will simulate. Each costs one
 * serialize/deserialize round trip plus one `activateBuff`, and an activation
 * happens at most once per turn, so this is cheap in a real game. It is
 * bounded anyway because the win-rate harness plays tens of thousands of them.
 */
const AI_REFINE_CANDIDATES = 10;

/**
 * Re-pick the last square by what the board looks like afterwards, not by what
 * is standing on the square now.
 *
 * The greedy sequence is kept as the incumbent and only replaced when a
 * simulated alternative is strictly better, so this can correct a blunder but
 * never invents a worse one. If the simulation cannot run at all (a card the
 * trial refuses to activate) the greedy answer stands unchanged.
 */
function refineLastSquarePick(
  game: NerfGame,
  color: Color,
  buffIndex: number,
  picks: BuffPick[],
  value: number,
  lastSquareStep: number,
  options: Square[],
): { picks: BuffPick[]; value: number } {
  if (lastSquareStep < 0 || options.length < 2) return { picks, value };
  const incumbent = aiScoreSequence(game, color, buffIndex, picks);
  if (incumbent == null) return { picks, value };

  const chosen = picks[lastSquareStep]?.square;
  let bestPicks = picks;
  let bestScore = incumbent;
  let tried = 0;
  for (const sq of options) {
    if (sq === chosen) continue;
    if (++tried > AI_REFINE_CANDIDATES) break;
    const alt = picks.map((p, i) => (i === lastSquareStep ? { ...p, square: sq } : p));
    const score = aiScoreSequence(game, color, buffIndex, alt);
    if (score != null && score > bestScore) {
      bestScore = score;
      bestPicks = alt;
    }
  }
  if (bestPicks === picks) return { picks, value };

  // The worth-firing gate downstream reads `value`, so it has to describe the
  // sequence actually being returned. Recomputed from the enemy material the
  // new picks land on, the same way the greedy pass counts it.
  const opp: Color = color === "w" ? "b" : "w";
  let newValue = 0;
  for (const p of bestPicks) {
    const piece = p.square !== undefined ? game.board.pieces[p.square] : null;
    if (piece && piece.color === opp) newValue = Math.max(newValue, AI_PIECE_VALUE[piece.type]);
  }
  // A sweep that catches three pawns on the way and ends on an empty square is
  // worth firing, and the landing-square rule alone would score it zero. The
  // simulated material gain is the honest floor for it.
  const gained = bestScore - aiPositionScore(game, color);
  return { picks: bestPicks, value: Math.max(newValue, gained) };
}

/** Collect a full pick sequence for an activated buff without a UI. Returns
 * null when the buff currently has no valid use, plus a rough value of the
 * best target so the caller can decide whether firing now is worth it. */
function aiCollectPicks(
  game: NerfGame,
  color: Color,
  buffIndex: number,
): { picks: BuffPick[]; value: number } | null {
  const opp: Color = color === "w" ? "b" : "w";
  const picks: BuffPick[] = [];
  let value = 0;
  const inst0 = game.buffs?.players[color].buffs[buffIndex];
  const def0 = inst0 && BUFF_BY_ID[inst0.id];
  const sacrifice = !!def0 && pickIsSacrifice(def0);
  // The candidates offered at the LAST square step, kept so the refinement
  // pass below can try the alternatives the greedy scorer passed over. Only
  // the last step is revisited: it is where a card's geometry resolves (a
  // sweep's endpoint, a teleport's destination), and re-searching every step
  // would multiply out for no benefit on the one and two pick cards that make
  // up nearly the whole library.
  let lastSquareStep = -1;
  let lastSquareOptions: Square[] = [];
  for (let step = 0; step < 16; step++) {
    const target = buffNextTarget(game, color, buffIndex, picks);
    if (!target) return refineLastSquarePick(game, color, buffIndex, picks, value, lastSquareStep, lastSquareOptions);
    if (target.kind === "square") {
      if (!target.squares.length) return null;
      lastSquareStep = picks.length;
      lastSquareOptions = target.squares;
      let best = target.squares[0];
      let bestScore = -Infinity;
      for (const sq of target.squares) {
        // A card that destroys its pick needs the opposite instinct from one
        // that protects it, so the scorer is chosen from the card, not fixed.
        const score = sacrifice
          ? aiSacrificeScore(game, color, sq)
          : aiSquareScore(game, color, sq);
        if (score > bestScore) {
          bestScore = score;
          best = sq;
        }
      }
      // For a sacrifice, the "value" of the pick is the NET trade, so the
      // caller can refuse a blast that catches nothing. Without this the
      // worth-firing gate only ever counted enemy pieces among the picks --
      // and a sacrifice card picks one of YOUR pieces, so it scored zero and
      // fired unconditionally. Funeral Pyre spent a piece per game for
      // whatever happened to be standing nearby.
      if (sacrifice) value = Math.max(value, (bestScore - 100) / 10);
      const piece = game.board.pieces[best];
      if (piece && piece.color === opp) value = Math.max(value, AI_PIECE_VALUE[piece.type]);
      picks.push({ square: best });
    } else {
      if (!target.options.length) return null;
      const best = target.options.reduce((a, b) => (b.tier > a.tier ? b : a));
      value = Math.max(value, best.tier);
      picks.push({ buffIndex: best.index });
    }
  }
  // The 16-step guard tripped, so the card never finished asking. Refine
  // anyway rather than returning a different shape from the normal path.
  return refineLastSquarePick(game, color, buffIndex, picks, value, lastSquareStep, lastSquareOptions);
}

/** Fire at most one of the bot's activated buffs, auto-picking targets.
 * Offensive cards wait for a target worth at least a minor piece so a
 * one-shot isn't wasted on a pawn; defensive/placement cards (no enemy piece
 * among the candidates) fire as soon as they are usable. Returns the used
 * card when a buff was activated (the board and effects may have changed),
 * so callers can tell the player what just hit the board. */
export function aiActivateBuffs(
  game: NerfGame,
  color: Color,
): { id: string; tier: Tier } | null {
  const choice = aiChooseBuffActivation(game, color);
  if (!choice) return null;
  const inst = game.buffs!.players[color].buffs[choice.buffIndex];
  if (activateBuff(game, color, choice.buffIndex, choice.picks)) {
    return { id: inst.id, tier: inst.tier };
  }
  return null;
}

/** The decision behind aiActivateBuffs, without applying it: the first held
 * buff worth firing right now plus its auto-picked targets, or null. Lets the
 * game server activate a house player's buff through its own recorded-action
 * flow so the match record stays identical to a human game's. */
export function aiChooseBuffActivation(
  game: NerfGame,
  color: Color,
): { buffIndex: number; picks: BuffPick[] } | null {
  const bs = game.buffs;
  if (!bs || bs.diff || game.result || game.board.turn !== color) return null;
  const ps = bs.players[color];
  const inDanger = gameInCheck(game, color);
  // Computed lazily: most calls never reach the protection branch.
  let oppAttacks: Set<Square> | null = null;
  for (let i = 0; i < ps.buffs.length; i++) {
    const inst = ps.buffs[i];
    const def = BUFF_BY_ID[inst.id];
    if (
      !def?.implemented ||
      def.kind !== "activated" ||
      inst.spent ||
      inst.nullified ||
      inst.usedActivation
    ) {
      continue;
    }
    // Belt-and-suspenders: usedActivation above already retires a fired card,
    // but the older state-based online check stays for clarity. Reusable cards
    // (spendOnUse: false) stay activatable until fired; once one is online
    // (bound to a piece or zone, or running) the bot must not burn its turns
    // re-activating it.
    if (
      def.spendOnUse === false &&
      (inst.state.sq != null ||
        inst.state.sqs != null ||
        inst.state.squares != null ||
        inst.state.active === true)
    ) {
      continue;
    }
    const collected = aiCollectPicks(game, color, i);
    if (!collected) continue;
    const hitsEnemy = collected.picks.some((p) => {
      if (p.buffIndex !== undefined) return true;
      const piece = p.square !== undefined ? game.board.pieces[p.square] : null;
      return !!piece && piece.color !== color;
    });
    // A sacrifice must actually pay: their material caught in the blast has to
    // exceed ours plus the piece being spent. Firing at a loss is worse than
    // not firing, and this card cannot be "saved for later" into a worse spot.
    if (pickIsSacrifice(def) && collected.value <= 0) continue;
    // Offensive one-shots hold out for a knight's worth of value.
    if (hitsEnemy && collected.value < 3) continue;
    // In check, the turn is not spare. A turn-consuming activation costs this
    // move (see activateBuff), and nothing here makes the check go away, so
    // firing one leaves the king still attacked with the escape move already
    // spent. That was near-fatal every time, and the rule below made it the
    // COMMON case: protective cards only fire when in danger, and "in danger"
    // is exactly being in check, so this bot reliably answered a check by
    // raising a shield that does not even cover the king.
    //
    // Free actions are exempt because they cost no turn, so the escape is
    // still available afterwards.
    if (inDanger && !def.freeAction) continue;
    // Protective cards wait for actual danger instead of firing blind -- but
    // "danger" is a piece of theirs actually under attack, NOT being in check.
    // Keying it to check was what forced the bad trade above: the only moment
    // a shield was allowed to fire was the one moment its turn could not be
    // spared. A threatened piece is the real cue, and it leaves the escape
    // move free.
    if (!hitsEnemy && def.category === "protection") {
      if (!oppAttacks) oppAttacks = attackedBy(game.board, color === "w" ? "b" : "w");
      const threatened = collected.picks.some(
        (p) => p.square !== undefined && oppAttacks!.has(p.square),
      );
      if (!threatened) continue;
    }
    return { buffIndex: i, picks: collected.picks };
  }
  return null;
}

export function resign(game: NerfGame, color: Color): NerfGame {
  if (game.result) return game;
  game.result = { winner: color === "w" ? "b" : "w", reason: "resignation" };
  return game;
}
